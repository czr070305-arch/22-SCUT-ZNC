#ifndef _V2_CFG_H_
#define _V2_CFG_H_

/*
 * vision2 参数表
 *
 * 本模块移植自 20 届学长(苏琦尧)的缩微光电视觉算法。
 * 与原 vision/ 的根本差异:
 *
 *   原 vision/:  大津法把灰度二值化 -> 逐行切"白线段" -> 从段里爬
 *   vision2   :  归一化梯度找"边沿" -> 用带方向的边沿(暗->亮/亮->暗)
 *                配对成白线 -> 纵向爬 + 横向扫
 *
 * 为什么这套更适合我们的赛道:
 *
 *   1) 归一化梯度对光照不敏感
 *        gx = (right-left) * 1024 / (right+left)
 *      这是比值, exposure 变了、蓝布反光变了, 边沿依然在同位置。
 *      彻底摆脱"阈值调不准"这个死结。
 *
 *   2) 白线有宽度, 就有左右两个边沿
 *      这是学长算法的核心假设, 我们的 20mm 胶带完全满足。
 *      左右边沿配对后中线 = (l+r)/2, 比"切段取中心"稳得多。
 *
 *   3) 直角弯用横向扫描, 不靠单个宽段判
 *      从中心往左右逐列扫, 每列找白线的上下边沿, 得到一条 2D 路径。
 *      拐点再大也能跟上。
 *
 *   4) 环岛用射线投票, 不靠"间距涨落"
 *      左右各打 5 条射线, 看某侧是否连续多列都能找到白线。
 *      不需要看到椭圆顶部合拢, 不受顶部裁剪影响。
 */

/* ---------- 图像尺寸 ---------- */
#define V2_W                    (188)
#define V2_H                    (120)

/* ---------- 边缘检测 ---------- */
/*
 * 归一化梯度阈值 (学长原值 150)
 *
 * 计算方式 (以水平为例):
 *   gx = (right_pixel - left_pixel) * 1024 / (right_pixel + left_pixel)
 *   edge 强度 = |gx| + |gy|
 *
 * 调小: 边缘更敏感, 噪声多
 * 调大: 只保留强边缘, 弱边沿(远处细线)可能丢失
 *
 * 注意: 这个阈值和曝光无关, 换场地基本不用改。
 */
#define V2_RATIO_THRES          (150)

/*
 * 黑区判断: 左右像素灰度之和低于这个值, 认为整个区域是黑的,
 * 不算边沿。用来屏蔽鱼眼黑角和纯黑背景。
 *
 * 学长原式: BLACK_THRES = RATIO_X_THRES * black_thres
 * 但 RATIO_X_THRES 是比值(1024 量纲), 而像素和是 0~510,
 * 两者直接相乘量纲不对。这里拆成独立的绝对阈值。
 *
 * 取值依据: 曝光 64 时蓝布灰度 20~40, 和 = 40~80。
 *         取 60 可以屏蔽纯黑(0~10), 同时保留暗蓝布的边沿。
 */
#define V2_BLACK_SUM            (60)

/* ---------- 白线宽度 ---------- */
/*
 * 一条白线在像素上的宽度范围。
 * 学长原值: LANE_MIN_WIDTH=3, LANE_MAX_WIDTH=25
 *
 * 我们的赛道: 20mm 胶带
 *   近处(画面底部) 约 10~16 px
 *   远处(画面顶部) 约 4~6 px
 *
 * 若车装得很低/很近, 近处会更宽, 需要加大 MAX。
 */
#define V2_LANE_MIN_W           (3)
#define V2_LANE_MAX_W           (30)

/* ---------- 搜索步长 ---------- */
/* 纵向: 每隔几行取一次中心点。4 行 = 30 个采样点, 够密 */
#define V2_VERT_DY              (4)

/* 横向: 直角弯时每隔几列取一次上下边沿。4 列 = 47 个采样点 */
#define V2_HORI_DX              (4)

/* 横向/纵向搜索的半宽: 以上一次的值为中心, 向两侧各搜这么多像素 */
#define V2_HALF_SEARCH_W        (15)

/* ---------- 丢线判定 ---------- */
/* 连续多少行/列找不到就停止爬 */
#define V2_LOST_MAX_Y           (7)
#define V2_LOST_MAX_X           (7)

/* ---------- 前瞻 ---------- */
/*
 * 取两个前瞻点做加权, 远处权重 track_ratio。
 *   FAR_1 = 55 行  (近, 反应快)
 *   FAR_2 = 70 行  (远, 提前量)
 *   ratio = 0.5    (各占一半)
 *
 * 学长原值就是 55 / 70 / 0.5。
 * 想要更稳(切内道多)就加大 ratio; 想要更灵敏就减小。
 */
#define V2_TRACK_FAR_1          (55)
#define V2_TRACK_FAR_2          (70)
#define V2_TRACK_RATIO          (0.5f)

/* ---------- 起点搜索 ---------- */
/* 从画面底部往上找起点的最大行数 */
#define V2_START_SEARCH_ROWS    (9)

/* 起点允许偏离上一帧底部点的横向距离 */
#define V2_START_TOL            (30)

/* ---------- 环岛 ---------- */
/*
 * 学长方案: 以当前跟踪点为原点, 左右各打 5 条竖射线,
 * 看某侧有几条能连续找到白线。
 *
 *   两侧都 >= 3 条  -> 十字
 *   左侧 >= 3 且 y 单调 -> 左环岛
 *   右侧 >= 3 且 y 单调 -> 右环岛
 *
 * 优点: 不需要看到椭圆顶部合拢, 顶部被裁掉也能识别。
 */
#define V2_CIRCLE_RAYS          (5)     /* 每侧射线数 */
#define V2_CIRCLE_DX_START      (10)    /* 第一条射线离中心的距离 */
#define V2_CIRCLE_DX_STEP       (5)     /* 射线间距 */

/*
 * check_group 的单调性判据: 相邻两条射线找到的 y 值差
 * 必须在 [pos_diff*2, pos_diff*25] 之间才算"在斜坡上"
 * 连续 3 条满足就判定为环岛入口的弧形。
 *
 * 这两个数是"白线在往斜上方走"的最小/最大斜率。
 */
#define V2_CIRCLE_SLOPE_MIN     (2)
#define V2_CIRCLE_SLOPE_MAX     (25)

/* 环岛确认所需的连续帧数, 防止单帧误判 */
#define V2_CIRCLE_CONFIRM_CNT   (3)

/* 环岛冷却帧数, 防止重复触发 */
#define V2_CIRCLE_COOLDOWN      (40)

/* ---------- 折角 ---------- */
/*
 * 识别到折角(直角弯)时, 额外给 err 加这么多偏置, 往弯里推。
 *
 * 为什么需要:
 *   前瞻点仍然落在"还没拐的那段竖直线上", 算出来的横偏很小,
 *   车会直着冲过去。加一个偏置相当于"提前打方向"。
 *
 * 22 是原 vision/ 用的值, 先用着; 过弯转过头就减小, 冲出去就加大。
 */
#define V2_CORNER_BIAS          (22.0f)

/* ---------- 摄像头 ---------- */
/*
 * 曝光时间。摄像头自己不保存曝光(set_exposure_time 不进 EEPROM),
 * 每次上电必须由 MCU 重新下发, 所以这里必须有一个确定值。
 *
 * 64 是实测值: 蓝布灰度 20~40, 白线 130~140, 动态范围够。
 */
#define V2_CAM_EXP_TIME         (64)

/* ---------- 显示 ---------- */
/* 每 N 帧刷一次屏 */
#define V2_DISP_EVERY_N         (5)

/* ---------- 调试 ---------- */
/* 1 = 屏幕上画边沿点(红色=左边沿 绿色=右边沿 黄色=中线) */
#define V2_DRAW_EDGES           (1)

#endif
