#ifndef _TASK_VOFA_H_
#define _TASK_VOFA_H_

/*
 * VOFA+ 上位机调参服务
 *
 * 不占页面, 挂在主循环里常驻运行, 显示和操作全在电脑上的 VOFA+ 完成.
 * 进 MOTOR TEST 页时自动交还底盘控制权, 避免两边抢同一个底盘.
 *
 * 上行 (FireWater 协议, 每个控制周期一帧, 上电后一直发, 停车也不停):
 *   tgtL,tgtR,actL,actR,outL,outR\n
 *   例如 500,500,498,497,3456,3400
 *   6 个通道依次是: 左目标 / 右目标 / 左实际 / 右实际 / 左占空比 / 右占空比
 *
 * 下行命令, 在 VOFA+ 左侧「命令」面板配置好再绑到滑块或按钮上:
 *   START                接管底盘 + 目标归零, 之后 TGT 才有效
 *   STOP                 停车 + 交还控制权
 *   TGT=500              左右同目标 (RPM), 仅接管后生效
 *   TGT=500,300          左右一起改
 *   TGL=500 / TGR=300    只改左边或只改右边, 左右各一个滑块时用
 *   STEP=500,5           自动阶跃: 目标在 0 和 500 之间每 5 秒切换
 *   STEP=0               停止阶跃, 保持当前目标
 *   KP=1.5 / KI=0.05 / KD=0     改速度环 PID, 写多少就是多少
 *                               支持小数, 最多 3 位, 任何时候都生效
 *   SAVE                 把当前 PID 写进 Flash, 掉电不丢
 *   LOAD                 从 Flash 重新读参数, 调乱了用它退回
 *   START / STOP / SAVE / LOAD 会回一行文本确认, 波形和数据帧照常发
 *
 * 分帧方式: 收到 \n \r ! 任意一个就认为一帧结束;
 *           另外最后字节之后连续 3 个控制周期(30ms)没有新数据也强制结束.
 *           这样 VOFA 命令框里写不写结束符都能用.
 *
 * 计时全部用 chassis 的控制周期计数, 不用主循环软件计时:
 *   主循环被 TFT 刷新拖慢时软件计时会漂, 而 TIM7 的周期计数是硬件级准的,
 *   波形点数也和速度环周期严格对齐, 不会重复也不会丢点.
 */

#include "zf_common_headfile.h"

//编译期开关
//1 = 调参固件, 0 = 比赛固件(不读串口不发波形, 主循环里等于空函数)
//调完参数记得改回 0 再烧比赛固件
#define VOFA_ENABLE             (1)

//单条命令最大长度(含结尾 \0)
#define VOFA_CMD_MAX_LEN        (40)

//命令帧超时, 单位是控制周期(1 周期 = 10ms)
//VOFA 的滑块如果设成"鼠标弹起后发送", 一次只发一条短命令, 30ms 足够
#define VOFA_FRAME_TIMEOUT_TICK (3)

//每圈最多消费的字节数
//防止电脑连发几十条命令时把主循环卡住, 剩下的留到下一圈继续
#define VOFA_RX_MAX_PER_CYCLE   (64)

//初始化: 清空串口残留 + 状态归零, 在 chassis_init() 之后调用
void vofa_init(void);

//主循环每圈调用
void vofa_run(void);

//交还底盘控制权(停车 + 关波形)
//进 MOTOR TEST 页做手动测试前调用, 否则两边会同时写目标速度
void vofa_release(void);

#endif
