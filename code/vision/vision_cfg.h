#define CFG_CORNER_FORK_ROWS (7)
#define CFG_CORNER_FORK_SEP  (8)
#define CFG_CORNER_END_MIN   (8)

/* 折角方向记忆帧数：车一转横臂就出画，没有记忆会"过弯一半又回正" */
#define CFG_CORNER_HOLD      (8)   /* 2026-11-24: 3->8，折角只看得到1~2帧，记忆太短会回正 */

/* 折角「连续多帧确认」（2026-11-24 新增）
 *
 * 折角判定（宽段判据 + path_end 补刀）每帧直接写 g_corner_dir，
 * 单帧误判会立刻把前瞻点搬到噪点上 -> 车猛打方向。
 * 打开 CFG_CORNER_ENABLE 之后这个风险必须堵住。
 *
 * 门控位置：track_build() 末尾，覆盖全部 3 个写入点。
 * 未确认时【连折角记忆一起清掉】——否则单帧噪声会被
 * CFG_CORNER_HOLD 放大 8 帧，门控等于没做。
 *
 * 调大：更保守，误报更少，但真折角响应更晚。
 * 调小：更灵敏，但可能误报。3 是折中。 */
#define CFG_CORNER_CONFIRM_TRACK  (3)

/* 元素探测窗口：路径顶部再往上多少行（不含白板区） */
#define CFG_ELEM_EXTRA_ROWS  (20)

#define CFG_ISLE_CONFIRM      (2)
/* 分叉形态持续这么多行才当环岛入口。
 * 10 行太松：直角弯的另一条腿在画面里也能撑到 20 多行（82 帧实测 23~49），
 * 于是每个弯都会被当成环岛。抬到 18，并要求连续帧确认（CFG_FORK_CONFIRM）。 */
#define CFG_ISLE_ENTRY_ROWS   (60)   /* 2026-11-24 环岛太早转: 14->22, 分叉入口门槛抬高 */
#define CFG_FORK_CONFIRM      (2)     /* 分叉/hit 必须连续这么多帧 */

/* 出岛后的冷却帧数：这段时间内不再接受新的环岛入口。
 * 这条赛道一圈两个环岛（先顺时针、后逆时针），两个岛之间隔着 3~4 米，
 * 50fps、1.5m/s 下大约 100~130 帧。冷却 120 帧既能挡住"出岛瞬间又被
 * 判成下一个岛"的连锁，又不会误伤真正的第二个岛。 */
#define CFG_ISLE_COOLDOWN     (100)   /* 2026-11-24: 120->60->100，出岛后2秒不许重进 */

/* 环岛"往弯里推"的误差偏置（像素当量）。
 * 仿真是用前馈差速 FF_ISLAND=20% 实现的，车上没有前馈通道，
 * 这里直接折成误差：KP≈2.5~7 时 60px 约等于 base 的 15~20% 差速。 */
/* 预赛没有岔路：分叉形态一律按环岛处理（和 VS 仿真同一套判据）。
 * 决赛有岔路时改回 0，同时把下面的 fork 入口关掉即可。 */
/* 行间跳变硬限制：本行候选点离上一行跟踪点超过这么多像素就不认。
 * 十字横臂会把跟踪点一把拽到横臂上（屏幕上看就是"爬成转弯"），
 * 99% 就发生在这一步。0 = 关闭。 */
#define CFG_ROW_STEP_MAX     (16)

#define CFG_NO_FORK          (1)

/* ---- 十字"直行锁"（2026-11-22 二改）----
 * 判到十字，就把整条中线锁成一条【竖线】，让车直接穿过去。
 *
 * 为什么要这么做：十字横臂是一段很宽的白。爬线一旦把"段中心"当成线，
 * 跟踪点就被拽到横臂上/横臂一侧，err 立刻偏出去 —— 屏幕上看到的就是
 * "遇到十字就拐弯，拐完沿着横臂绕圈出不来"。
 * 锁成竖线等于明确告诉控制层：这里没有弯，往前走。
 *
 * CFG_CROSS_LOCK_MAX：最多锁这么多帧（50fps 下 30 帧 = 0.6s），
 * 防止十字被误判时一直锁着把车带歪。 */
#define CFG_CROSS_LOCK        (1)
#define CFG_CROSS_LOCK_MAX    (30)
/* 十字过后再保持【不许判折角】的帧数。
 * 实测（pic\num 第 79/81 张）：十字刚过去那几帧，横臂残影是一段宽白，
 * 折角判据会把前瞻点甩到横臂右端（x=136，err 一下 +63），车就右打死、
 * 然后绕圈出不来。这段时间禁止判折角，让它老老实实直行。 */
#define CFG_CROSS_AFTER       (12)
/* 横臂末端"竖壁"过滤。
 * 十字横臂的两端各有一小段竖直的白（贴纸收边），它就是窄段，
 * 正好落进"支线/折角另一条腿"的判据里 —— 车就会当成"线往那边拐"。
 * 判据：同一行里如果有一段比 CFG_CROSS_W 还宽的横臂，且候选窄段
 * 紧贴着它的某一端（<= CFG_ARM_END_GAP 像素），这段就是横臂端头，不算支线。
 * 只在 g_cross_rows >= 1（十字附近）生效，环岛/普通弯完全不受影响。 */
#define CFG_ARM_END_FILTER    (1)
#define CFG_ARM_END_GAP       (8)

/* ---- 环岛"咬边"放宽（2026-11-22 二改）----
 * 进岛时 prefer_side 要咬的是环的那条【外弧】，它比普通岔路支线更宽、更远。
 * 原来 find_run_prefer 只认 <=38px 宽、<=34px 远的段，环岛入口那条弧
 * 直接被滤掉 → 咬不到边 → 车直着开过去，永远进不了岛。 */
#define CFG_ISLE_PREFER_WMAX  (90)
#define CFG_ISLE_PREFER_DMAX  (45)


/* ★ 2026-11-22 晚：60px 的偏置把"误判成环岛"的代价放大了 10 倍 ——
 * 车一旦在直角弯被误判，就会带着 60px 的固定偏置硬拐，看着就是"没到环岛
 * 就转弯 / 在十字里绕圈"。现在 prefer_side 已经全程咬边，跟踪点本身就在
 * 环的那条边上，err 自然会给出转弯量，这个偏置不再需要。
 * 想再给一点"推力"就从 15~20 开始试，不要直接回 60。 */
/* 统一方向判定的最小偏移（2026-11-24 新增）
 * unified_island_side() 用：路径顶部相对底部跟踪点的平均横向偏移
 * 超过这个值才认为是路径弯向那边，否则退回传入的 fallback。
 * 8 像素约等于一个线宽，太小会被爬线噪声带偏。 */
#define CFG_ISLE_SIDE_MIN_PX   (8)

#define CFG_ISLE_ERR_PUSH    (35.0f)


/* 状态机超时（帧，50fps）。超时强制回普通状态，防卡死
 *
 *   元素判错时最怕"卡在里面出不来"：比如把反光当成环岛、g_island_on
 *   一直不清，车就会永远走"咬边"逻辑。超时是最后一道保险。 */
#define CFG_STATE_MAX_CORNER (30)
#define CFG_STATE_MAX_CROSS  (40)
#define CFG_STATE_MAX_ISLAND (250)

/* 元素里的速度系数（%）
 *
 *   (!) 实际效果受限: ctrl.c 有 base_floor = CTRL_WHEEL_MIN_RPM(520) +
 *     CTRL_TURN_MIN_RPM(160) = 680 RPM，而巡航 800 RPM 时:
 *        70% -> 560 -> 被抬回 680 (实际 85%)
 *        60% -> 480 -> 被抬回 680 (实际 85%)
 *     也就是这些系数目前【基本不生效】，除非把巡航提到 971 RPM 以上。
 *     保留是为了数据通路完整。 */
#define CFG_SPD_CORNER       (100)  /* 2026-11-22: 70 -> 100，关闭元素降速，消除误判导致的顿挫 */
#define CFG_SPD_CROSS        (100)
#define CFG_SPD_ISLAND       (100)  /* 2026-11-22: 60 -> 100，关闭元素降速，消除误判导致的顿挫 */

/* ---------- 元素降速的防抖（2026-11-21 实测加）----------
 *
 * 实测数据（CRUIS=1000，直道跑 84 秒）：
 *   spd   : 100 占 272 帧，70 占 169 帧
 *   state : 0 占 272 帧，1 占 169 帧
 *   cdir  : 0 占 272 帧，+1 占 145 帧，-1 占 24 帧
 *
 *   48 次 ±300 RPM 的目标跳变，全部对应 spd 在 100 <-> 70 之间切换。
 *   现象是车"前后一顿一顿"（两轮同向骤降），不偏方向。
 *
 * 原因：state_update() 只要 g_corner_dir != 0 一帧就进直角弯状态、
 *      立刻把速度砍到 70%。而 post_detect_corner() 判据偏松，
 *      直道上会零星误报。
 *
 * 两道防抖：
 *
 * CFG_CORNER_CONFIRM
 *   g_corner_dir 必须连续这么多帧指向同一方向，才算真直角弯。
 *   真直角弯会连续几十帧成立，零星误报只有 1~2 帧。
 *   3 帧 = 60ms 延迟，对降速时机影响可忽略。
 *
 * CFG_SPD_SLEW
 *   速度建议每帧最多变化这么多（百分点）。
 *   100 -> 70 需要 (100-70)/2 = 15 帧 = 300ms。
 *   即使确认条件偶有波动，base 也是平滑变化的，不会再顿。
 *   0 = 关闭渐变（回到旧行为）。
 */
#define CFG_CORNER_CONFIRM   (3)
#define CFG_SPD_SLEW         (2)



