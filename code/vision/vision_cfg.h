/* ==================== 前瞻点与误差权重（tune 模块） ====================
 *
 * 下面两个参数已经挪到 TRACK 页在线可调（Flash 保存）：
 *   CFG_LOOKAHEAD     ->  TUNE_LOOKAHEAD   屏幕 LOOK   20~80（行）
 *   CFG_ERR_SLOPE_W   ->  TUNE_SLOPE_W     屏幕 SLOPE   0~12
 *
 * 前瞻点 = 从车头中线往上数 N 行的位置，track_steer() 瞄准它。
 *   N 小 = 看脚下，切弯急、直线噪声敏感
 *   N 大 = 看远处，切弯平缓提前，但可能瞄到赛道外的噪点
 *
 * 斜率项：底部 14 行中线的倾斜程度，提供"提前打方向"的预判量。
 * 权重调大 = 提前打方向但直线会抖；调小 = 反应慢。
 *
 * 横向偏差权重 CFG_ERR_OFF_W 保留为宏：
 *   err = dx * OFF_W 和 KP 是纯乘法关系，
 *   挪到参数表就是和 KP 重复，只保留一个出口。
 */
#define CFG_ERR_OFF_W        (1.0f)

/* ---------- 斜率项的启用条件 ----------
 *
 * 直线的真实斜率是 0，斜率项在直线上贡献的全是爬线噪声。
 * 下面两组门槛让斜率项只在"确实在弯道"时生效。
 *
 * SPAN:
 *   算斜率要取"车头往上 14 行内第一个有效行"。如果那一行恰好
 *   断了一帧，分母会缩到 5、3、甚至 1，噪声被放大十几倍。
 *   分母不足这么多行时，本帧干脆不用斜率项。
 *
 * GATE_LO / GATE_HI:
 *   按横向偏差 |dx|（前瞻点离画面中心的像素数）做渐变门控——
 *   |dx| <= LO 不用；|dx| >= HI 全量；中间线性过渡。
 *
 *   为什么不 |dx|>0 就启用:
 *     弯道入口恰恰是"横向偏差还小、斜率已经大"的那一刻，
 *     一刀切会丢掉最该提前的几帧，切弯反而变晚。
 *
 *   为什么不用 err 做门控:
 *     err 里已经混进了斜率项本身，拿它当判据会互相污染。
 *     dx 是纯横向偏差，干净。
 *
 * 实测（188 宽，鱼眼校正后）:
 *   直线 |dx| 一般 < 8
 *   弯道入口 |dx| 从 8 涨到 25 左右
 */
#define CFG_SLOPE_MIN_SPAN   (10)
#define CFG_SLOPE_GATE_LO    (6.0f)
#define CFG_SLOPE_GATE_HI    (22.0f)

